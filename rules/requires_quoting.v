// requires_quoting ports requiresQuoting(name): the name is empty or some of its UTF-16 code units
// is not an identifier character.
fn requires_quoting(name string) bool {
	if name.len == 0 {
		return true
	}
	for i, code in name.runes() {
		// A character outside the BMP is two surrogates, which are not identifier characters.
		if u32(code) > 0xFFFF {
			return true
		}
		if i == 0 {
			if !ts_is_identifier_start(u32(code)) {
				return true
			}
		} else if !ts_is_identifier_part(u32(code)) {
			return true
		}
	}
	return false
}

// ts_is_identifier_start ports TypeScript's isIdentifierStart for a UTF-16 code unit.
fn ts_is_identifier_start(code u32) bool {
	return (code >= `A` && code <= `Z`) || (code >= `a` && code <= `z`) || code == `$`
		|| code == `_` || (code > 127 && ts_unicode_lookup(code, ts_identifier_start_ranges))
}

// ts_is_identifier_part ports TypeScript's isIdentifierPart (without the JSX variant).
fn ts_is_identifier_part(code u32) bool {
	return (code >= `A` && code <= `Z`) || (code >= `a` && code <= `z`)
		|| (code >= `0` && code <= `9`) || code == `_` || code == `$`
		|| (code > 127 && ts_unicode_lookup(code, ts_identifier_part_ranges))
}

// ts_unicode_lookup ports lookupInUnicodeMap: a binary search in the pairs of a table.
fn ts_unicode_lookup(code u32, ranges []u16) bool {
	mut lo := 0
	mut hi := ranges.len / 2
	for lo < hi {
		mid := (lo + hi) / 2
		if code < u32(ranges[2 * mid]) {
			hi = mid
		} else if code > u32(ranges[2 * mid + 1]) {
			lo = mid + 1
		} else {
			return true
		}
	}
	return false
}
