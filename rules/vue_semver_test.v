module rules

// vue_semver.v against node-semver 7.8.6: whether each range is a subset of the ranges
// vue/no-unsupported-features checks (1 or 0 per range of `vsem_test_doms`, `invalid` when Range
// throws), as `semver.subset(new Range(sub), new Range(dom))` gives (generated with node).

const vsem_test_doms = ['>=2.5.0 <3.0.0', '>=2.6.0', '>=2.7.0', '>=3.0.3 || >=2.7.0 <3.0.0', '>=3.0.0',
	'>=3.1.0', '>=3.2.0', '>=3.2.0 || >=2.6.0-beta.1 <=2.6.0-beta.3', '>=3.3.0', '>=3.4.0']

fn test_vsem_subset() {
	r := vsem_re()!
	cases := [
		['^2.4.0', '0000000000'],
		['^2.5.0', '1000000000'],
		['^2.6.0', '1100000000'],
		['^2.7.0', '1111000000'],
		['^3.0.0', '0110100000'],
		['^3.0.3', '0111100000'],
		['^3.1.0', '0111110000'],
		['^3.2.0', '0111111100'],
		['^3.3.0', '0111111110'],
		['^3.4.0', '0111111111'],
		['2.5.99', '1000000000'],
		['2.6.0-beta.1', '0000000100'],
		['2.6.0-beta.2', '0000000100'],
		['2.6.0-beta.3', '0000000100'],
		['2.7.0', '1111000000'],
		['3.1.0', '0111110000'],
		['3.2.0', '0111111100'],
		['3.4.0', '0111111111'],
		['>=2.0.0', '0000000000'],
		['~2.6', '1100000000'],
		['2.x', '0000000000'],
		['3', '0110100000'],
		['*', '0000000000'],
		['', '0000000000'],
		['>=3.0.3', '0111100000'],
		['>3.1', '0111111100'],
		['<=3.2.x', '0000000000'],
		['> 3.0.0 < 3.5.0', '0110100000'],
		['1.2.3 - 3.4', '0000000000'],
		['2.6.0 - 3', '0100000000'],
		['3.2.0 || 2.6.0-beta.2', '0000000100'],
		['^2.6.0-beta.1', '0000000000'],
		['~3.2.0-rc.1', '0000000000'],
		['=3.4.0', '0111111111'],
		['v3.4.0', '0111111111'],
		['>=3.3.0 <3.3.0', '1111111111'],
		['^0.0.1', '0000000000'],
		['^0.1.2', '0000000000'],
		['~1', '0000000000'],
		['3.x || 2.7.x', '0110000000'],
		['>=2.7.0 <3.0.0', '1111000000'],
		['^3.2.0+build.1', '0111111100'],
		['>3.2.0-0', '0000000000'],
		['<4.0.0-0 >=3.2.0', '0111111100'],
		['  ^  3.2.0  ', '0111111100'],
		['~> 3.2', '0111111100'],
		['> =3.1.0', '0111110000'],
		['3.2.0 3.2.0', '0111111100'],
		['3.2.0 3.3.0', '1111111111'],
		['>=3.2.0-alpha.10', '0000000000'],
		['>=3.2.0-alpha.9', '0000000000'],
		['>=3.2.0-0 <3.2.0', '0000000000'],
		['foo', 'invalid'],
		['1.2.3.4', 'invalid'],
		['^3.2.0 bar', 'invalid'],
		['99999999999999999.0.0', 'invalid'],
		['^9007199254740991.0.0', 'invalid'],
		['||', '0000000000'],
		['3.2.0 ||  ', '0000000000'],
		['<3.2.0-0', '0000000000'],
		['>=3.2.0-beta <3.2.0-beta.2', '0000000000'],
		['1.2.3-01', 'invalid'],
	]
	for c in cases {
		sub := r.range(c[0]) or {
			assert c[1] == 'invalid', c[0]
			continue
		}
		mut got := ''
		for d in vsem_test_doms {
			got += if r.subset(sub, r.range(d)!)! { '1' } else { '0' }
		}
		assert got == c[1], c[0]
	}
}
