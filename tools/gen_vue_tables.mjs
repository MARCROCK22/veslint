// Generates vue/tables.v, the tables of vue-eslint-parser 10.4.2's HTML parser that vue/ ports:
// its named character references (src/html/util/entities.ts, by length, longest first), the
// Windows-1252 replacements of numeric references (alternative-cr.ts), the tag name sets of
// tag-names.ts and the name maps of attribute-names.ts, read from the sources embedded in the
// source map of the published package in build/upstream/vue-deps; and the implicit variables
// typescript-eslint's scope manager 8.72.2 puts in the global scope of a template expression (the
// lib `esnext` with its dependencies, the default of `analyze`, and `const`).
//
//   node tools/gen_vue_tables.mjs vue/tables.v && v fmt -w vue/tables.v
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const MAP = path.join(ROOT, 'build/upstream/vue-deps/node_modules/vue-eslint-parser/dist/index.cjs.map');
const map = JSON.parse(fs.readFileSync(MAP, 'utf8'));
const source = name => map.sourcesContent[map.sources.findIndex(s => s.endsWith(name))];

// The value after the first `=` of `export const NAME`, as JavaScript.
function constant(text, name) {
  const at = text.indexOf(`export const ${name}`);
  const start = text.indexOf('=', at) + 1;
  const end = text.indexOf('\n\n', start);
  return text.slice(start, end === -1 ? undefined : end).trim();
}

const entitySets = JSON.parse(constant(source('html/util/entities.ts'), 'entitySets'));
const alternative = eval(constant(source('html/util/alternative-cr.ts'), 'alternativeCR').replace(/^new Map\(/, '(').replace(/\)$/, ')'));
const tags = source('html/util/tag-names.ts');
const set = name => eval(constant(tags, name).replace(/^new Set\(/, '(').replace(/\)$/, ')'));
const attrs = source('html/util/attribute-names.ts');
const pairs = name => eval(constant(attrs, name).replace(/^new Map\(/, '(').replace(/\)$/, ')'));

// quote writes a V string literal; other than printable ASCII as the \x escapes of its UTF-8.
const q = s => "'" + [...s].map(c => (c.codePointAt(0) < 0x20 || c.codePointAt(0) > 0x7e || c === "'" || c === '\\' ? [...Buffer.from(c, 'utf8')].map(b => `\\x${b.toString(16).padStart(2, '0')}`).join('') : c)).join('') + "'";

const out = [];
out.push('// Code generated by tools/gen_vue_tables.mjs from vue-eslint-parser 10.4.2; DO NOT EDIT.');
out.push('module vue', '');
out.push('// entity_lengths are the lengths of the names of the named character references (without');
out.push("// `&`, with the `;` when they have one), longest first: the tokenizer tries them in this order.");
out.push(`const entity_lengths = [${entitySets.map(s => s.length).join(', ')}]`, '');
out.push('// entities maps the name of each named character reference to its text.');
out.push('const entities = {');
for (const s of entitySets)
  for (const [name, cps] of Object.entries(s.entities)) out.push(`\t${q(name)}: ${q(String.fromCodePoint(...cps))}`);
out.push('}', '');
out.push('// alternative_cr maps the C1 controls of numeric references to their Windows-1252 characters.');
out.push('const alternative_cr = {');
for (const [k, v] of alternative) out.push(`\tu32(${k}): u32(${v})`);
out.push('}', '');
const setNames = {
  HTML_VOID_ELEMENT_TAGS: 'html_void_element_tags',
  HTML_CAN_BE_LEFT_OPEN_TAGS: 'html_can_be_left_open_tags',
  HTML_NON_FHRASING_TAGS: 'html_non_phrasing_tags',
  HTML_RCDATA_TAGS: 'html_rcdata_tags',
  HTML_RAWTEXT_TAGS: 'html_rawtext_tags',
};
for (const [js, v] of Object.entries(setNames)) out.push(`const ${v} = [${[...set(js)].map(q).join(', ')}]`, '');
const svg = [...set('SVG_TAGS')].filter(n => /[A-Z]/.test(n));
out.push('// svg_element_name_map maps the lower-cased names of the SVG elements with capitals to them.');
out.push('const svg_element_name_map = {');
for (const n of svg) out.push(`\t${q(n.toLowerCase())}: ${q(n)}`);
out.push('}', '');
out.push('const svg_attribute_name_map = {');
for (const [k, v] of pairs('SVG_ATTRIBUTE_NAME_MAP')) out.push(`\t${q(k)}: ${q(v)}`);
out.push('}', '');
out.push('const mathml_attribute_name_map = {');
for (const [k, v] of pairs('MATHML_ATTRIBUTE_NAME_MAP')) out.push(`\t${q(k)}: ${q(v)}`);
out.push('}', '');
const { lib } = (await import(path.join(ROOT, 'build/upstream/vue-deps/node_modules/@typescript-eslint/scope-manager/dist/lib/index.js'))).default;
const libs = new Set([lib.get('esnext')]);
for (const l of libs) for (const dep of l.libs) libs.add(dep);
const globals = new Map();
for (const l of libs)
  for (const [name, v] of l.variables) {
    const old = globals.get(name) ?? 0;
    globals.set(name, old | (v.isTypeVariable ? 1 : 0) | (v.isValueVariable ? 2 : 0));
  }
globals.set('const', 1);
out.push('// lib_globals are the implicit variables of the global scope of a template expression, by');
out.push('// name: 1 a type, 2 a value, 3 both.');
out.push('const lib_globals = {');
for (const [name, flags] of [...globals].sort((a, b) => (a[0] < b[0] ? -1 : 1))) out.push(`\t${q(name)}: u8(${flags})`);
out.push('}', '');
fs.writeFileSync(process.argv[2] ?? path.join(ROOT, 'vue/tables.v'), out.join('\n'));
console.log(`${entitySets.reduce((n, s) => n + Object.keys(s.entities).length, 0)} entities`);
