// Generates tsgo/ast_properties.v: the child properties of each SyntaxKind in the binary AST of the
// pinned TypeScript (childProperties of dist/api/node/protocol.generated.js), which
// AstTree.node_child needs. Dev-time only: run `node tools/gen_ast_properties.mjs` (with V=<path to
// v> if `v` is not in PATH) after changing the TypeScript version; it formats the output with v fmt.
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { pathToFileURL } from 'node:url';

const root = path.resolve(import.meta.dirname, '..');
const dist = path.join(root, 'node_modules/typescript/dist');
const { childProperties } = await import(pathToFileURL(path.join(dist, 'api/node/protocol.generated.js')).href);
const { SyntaxKind } = await import(pathToFileURL(path.join(dist, 'ast/index.js')).href);
const { version } = JSON.parse(fs.readFileSync(path.join(root, 'node_modules/typescript/package.json'), 'utf8'));

// The name of a kind, without the First*/Last* aliases.
const kindName = kind => Object.keys(SyntaxKind).find(n => SyntaxKind[n] === kind && !/^(First|Last)/.test(n));
const entries = Object.entries(childProperties)
  .map(([kind, properties]) => [Number(kind), properties])
  .sort((a, b) => a[0] - b[0]);
const lines = [
  '// Code generated by tools/gen_ast_properties.mjs; DO NOT EDIT.',
  'module tsgo',
  '',
  `// child_properties are the child properties of each SyntaxKind in the binary AST of TypeScript`,
  `// ${version}, in order (childProperties of dist/api/node/protocol.generated.js); the child mask of a`,
  '// node tells which of them it has (see AstTree.node_child).',
  'const child_properties = {',
  ...entries.map(([kind, properties], i) =>
    `\t${i === 0 ? `u32(${kind})` : kind}: [${properties.map(p => `'${p}'`).join(', ')}] // ${kindName(kind)}`),
  '}',
  '',
];
const output = path.join(root, 'tsgo/ast_properties.v');
fs.writeFileSync(output, lines.join('\n'));
execFileSync(process.env.V ?? 'v', ['fmt', '-w', output], { stdio: 'inherit' });
