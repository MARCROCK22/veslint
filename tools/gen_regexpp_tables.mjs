// Generates regexpp/tables.v from regexpp 4.12.2's index.js (the data is not exported, so it is read from the source text).
import fs from "node:fs";
const src = fs.readFileSync(process.argv[2], "utf8");
function restoreRanges(data) {
	let last = 0;
	return data.split(" ").map((s) => (last += parseInt(s, 36) | 0));
}
function rangesOf(fn) {
	const m = src.match(new RegExp(`function ${fn}\\(\\) \\{\\s*return restoreRanges\\("([^"]*)"\\);`));
	if (!m) throw new Error(fn);
	return restoreRanges(m[1]);
}
function dataSet(name) {
	const m = src.match(new RegExp(`const ${name} = new DataSet\\(((?:"[^"]*",?\\s*){9})\\);`));
	if (!m) throw new Error(name);
	const parts = [...m[1].matchAll(/"([^"]*)"/g)].map((x) => x[1]);
	if (parts.length !== 9) throw new Error(name + " parts");
	// year -> names; first year a name appears wins
	const out = new Map();
	parts.forEach((raw, i) => {
		const year = 2018 + i;
		// DataSet splits "" into [""], a set holding the empty string
		for (const n of raw.split(" ")) if (!out.has(n)) out.set(n, year);
	});
	return out;
}
function vRanges(name, arr) {
	let s = `const ${name} = [\n`;
	for (let i = 0; i < arr.length; i += 12) s += "\t" + arr.slice(i, i + 12).join(", ") + ",\n";
	return s + "]!\n\n";
}
function vMap(name, m) {
	let s = `const ${name} = {\n`;
	for (const [k, y] of [...m].sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0))) s += `\t'${k}': ${y}\n`;
	return s + "}\n\n";
}
let out = "// Generated by tools/gen_tables.mjs from @eslint-community/regexpp 4.12.2 (index.js). Do not edit.\nmodule regexpp\n\n";
out += "// Sorted [min, max] code point pairs of ID_Start beyond ASCII (initLargeIdStartRanges).\n";
out += vRanges("large_id_start_ranges", rangesOf("initLargeIdStartRanges"));
out += "// Sorted [min, max] code point pairs of ID_Continue minus ID_Start beyond ASCII (initLargeIdContinueRanges).\n";
out += vRanges("large_id_continue_ranges", rangesOf("initLargeIdContinueRanges"));
out += "// Each map gives the first DataSet year (es2018..es2026) that lists the name; the empty string is listed because\n// regexpp splits \"\" into [\"\"].\n";
out += vMap("gc_value_years", dataSet("gcValueSets"));
out += vMap("sc_value_years", dataSet("scValueSets"));
out += vMap("bin_property_years", dataSet("binPropertySets"));
out += vMap("bin_property_of_strings_years", dataSet("binPropertyOfStringsSets"));
fs.writeFileSync(process.argv[3], out);
