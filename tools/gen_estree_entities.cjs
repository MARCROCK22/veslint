// Generates estree/entities.v from the jsx/xhtml-entities.js of the installed typescript-estree.
const e = require(require('path').join(__dirname, '../build/eval/spider-byte/node_modules/@typescript-eslint/typescript-estree/dist/jsx/xhtml-entities.js')).xhtmlEntities;
const version = require(require('path').join(__dirname, '../build/eval/spider-byte/node_modules/@typescript-eslint/typescript-estree/package.json')).version;
let s = `module estree\n\n// Generated by tools/gen_estree_entities.cjs from typescript-estree ${version} (jsx/xhtml-entities.js); do\n// not edit.\n\n// xhtml_entities maps the name of an XHTML entity to its character.\nconst xhtml_entities = {\n`;
for (const [k, v] of Object.entries(e)) {
	if (v.length !== 1) throw new Error(k);
	s += `\t'${k}': u32(${v.charCodeAt(0)})\n`;
}
s += '}\n';
require('fs').writeFileSync(process.argv[2], s);
console.log(Object.keys(e).length);
