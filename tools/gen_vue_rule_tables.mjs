// Generates rules/vue_tables.v, the tables of eslint-plugin-vue 10.12.1's lib/utils that the vue/*
// rules use: the well-known HTML, SVG and MathML element names, the void elements, the deprecated
// HTML elements, the inline non-void elements, the key aliases of v-on modifiers, the key names
// of the deprecated key codes (keycode-to-key.ts), the built-in components, the reserved words of
// JavaScript and the SVG attributes that are not kebab-case, read from the clone in
// build/upstream/vue.
//
//   node tools/gen_vue_rule_tables.mjs && v fmt -w rules/vue_tables.v
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const UTILS = path.join(ROOT, 'build/upstream/vue/lib/utils');
const json = name => JSON.parse(fs.readFileSync(path.join(UTILS, name), 'utf8'));

// A V string literal of printable ASCII (the tables have nothing else).
const q = s => {
  if (!/^[\x20-\x7e]*$/.test(s)) throw new Error(`not printable ASCII: ${JSON.stringify(s)}`);
  return `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$')}'`;
};
const set = (name, doc, values) => [
  `// ${doc}`,
  `const ${name} = {`,
  ...[...new Set(values)].sort().map(v => `\t${q(v)}: true`),
  '}',
  '',
];

// keycode-to-key.ts: `export default { 8: 'backspace', … }`.
const keycodes = fs.readFileSync(path.join(UTILS, 'keycode-to-key.ts'), 'utf8');
const keyOfCode = [...keycodes.matchAll(/^\s*(\d+): '([^']*)'/gm)].map(m => [Number(m[1]), m[2]]);
if (keyOfCode.length < 10) throw new Error('keycode-to-key.ts: unexpected shape');

// vue2-builtin-components.ts and vue3-builtin-components.ts: `export default [ 'template', … ]` (the
// second spreads the first).
const builtinComponents = ['vue2-builtin-components.ts', 'vue3-builtin-components.ts'].flatMap(name =>
  [...fs.readFileSync(path.join(UTILS, name), 'utf8').matchAll(/^\s*'([^']*)',?$/gm)].map(m => m[1]));
if (builtinComponents.length < 14) throw new Error('vue*-builtin-components.ts: unexpected shape');

const out = [
  '// Code generated by tools/gen_vue_rule_tables.mjs from eslint-plugin-vue 10.12.1; DO NOT EDIT.',
  'module rules',
  '',
  ...set('vue_html_element_names', 'html-elements.json: the well-known HTML element names.', json('html-elements.json')),
  ...set('vue_svg_element_names', 'svg-elements.json: the well-known SVG element names.', json('svg-elements.json')),
  ...set('vue_math_element_names', 'math-elements.json: the well-known MathML element names.', json('math-elements.json')),
  ...set('vue_void_element_names', 'void-elements.json: the void HTML element names.', json('void-elements.json')),
  ...set('vue_deprecated_html_element_names', 'deprecated-html-elements.json: the deprecated HTML element names.',
    json('deprecated-html-elements.json')),
  ...set('vue_inline_non_void_element_names', 'inline-non-void-elements.json: the inline elements that are not void.',
    json('inline-non-void-elements.json')),
  ...set('vue_key_aliases', 'key-aliases.json: the key names a v-on modifier may be (valid-v-on).', json('key-aliases.json')),
  '// vue_keycode_keys is keycode-to-key.ts: the key name of each deprecated key code.',
  'const vue_keycode_keys = {',
  ...keyOfCode.map(([code, key]) => `\t${code}: ${q(key)}`),
  '}',
  '',
  ...set('vue_builtin_component_names', 'vue2-builtin-components.ts and vue3-builtin-components.ts: the built-in components.',
    builtinComponents),
  ...set('vue_js_reserved_names', 'js-reserved.json: the reserved words of JavaScript (this-in-template).', json('js-reserved.json')),
  ...set('vue_svg_attributes_weird_case', 'svg-attributes-weird-case.json: the SVG attributes that are not kebab-case.',
    json('svg-attributes-weird-case.json')),
];
fs.writeFileSync(path.join(ROOT, 'rules/vue_tables.v'), out.join('\n'));
console.log('rules/vue_tables.v written');
