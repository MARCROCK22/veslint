// node tools/gen_svelte_rule_tables.mjs > rules/svelte_tables.v
//
// The tables of eslint-plugin-svelte 3.24.1's src/utils for the svelte/* rules, from the clone in
// build/upstream/svelte, as V constants: element-types.ts (void, SVG and MathML elements) and
// events.ts (EVENT_NAMES).
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const source = fs.readFileSync(path.join(ROOT, 'build/upstream/svelte/packages/eslint-plugin-svelte/src/utils/element-types.ts'), 'utf8');
const tables = {};
for (const m of source.matchAll(/export const (\w+) = \[([^\]]*)\]/g)) {
  tables[m[1]] = [...m[2].matchAll(/'([^']*)'/g)].map(s => s[1]);
}
const events = fs.readFileSync(path.join(ROOT, 'build/upstream/svelte/packages/eslint-plugin-svelte/src/utils/events.ts'), 'utf8');
const eventNames = /export const EVENT_NAMES: string\[\] = \[([^\]]*)\]/.exec(events);
if (!eventNames) throw new Error('no EVENT_NAMES in events.ts');
tables.EVENT_NAMES = [...eventNames[1].matchAll(/'([^']*)'/g)].map(s => s[1]);
const names = { voidElements: 'sv_void_elements', svgElements: 'sv_svg_elements', mathmlElements: 'sv_mathml_elements', EVENT_NAMES: 'sv_event_names' };
let out = `module rules

// Generated by tools/gen_svelte_rule_tables.mjs from eslint-plugin-svelte 3.24.1's
// src/utils/element-types.ts and events.ts: do not edit.
`;
for (const [name, constName] of Object.entries(names)) {
  if (!tables[name]) throw new Error(`no ${name} in element-types.ts`);
  out += `\n// ${name}\nconst ${constName} = [${tables[name].map(s => `'${s}'`).join(', ')}]\n`;
}
process.stdout.write(out);
