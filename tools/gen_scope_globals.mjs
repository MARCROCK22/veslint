// Generates rules/scope_globals.v: the globals ESLint adds to the global scope for each
// ecmaVersion and for CommonJS (conf/globals.js and conf/ecma-version.js of the ESLint installed
// by tests/eval_spider_byte.sh in build/eval), and the implicit variables of every lib of
// typescript-eslint's scope manager (dist/lib of the @typescript-eslint/scope-manager installed
// there), with the libs each one includes.
// Dev-time only: run `node tools/gen_scope_globals.mjs` (with V=<path to v> if `v` is not in
// PATH) after changing the ESLint or typescript-eslint version; it formats the output with v fmt.
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { execFileSync } from 'node:child_process';

const root = path.resolve(import.meta.dirname, '..');
const eslint = path.join(root, 'build/eval/spider-byte/node_modules/eslint');
const require = createRequire(import.meta.url);
const globals = require(path.join(eslint, 'conf/globals.js'));
const { LATEST_ECMA_VERSION } = require(path.join(eslint, 'conf/ecma-version.js'));
const { version } = JSON.parse(fs.readFileSync(path.join(eslint, 'package.json'), 'utf8'));
// In the order of conf/globals.js: the order ESLint adds them to the global scope in.
const names = Object.keys(globals[`es${LATEST_ECMA_VERSION}`]);
// The versions with globals, and for each global the first one that has it.
const versions = Object.keys(globals)
  .filter(key => /^es\d+$/.test(key))
  .map(key => Number(key.slice(2)))
  .sort((a, b) => a - b);
const first = new Map();
for (const v of versions) {
  const of = Object.keys(globals[`es${v}`]);
  for (const name of of) if (!first.has(name)) first.set(name, v);
  // The globals of a version are those of the latest one that existed by then, in the same
  // order, and all of them are read-only.
  const expected = names.filter(name => first.has(name) && first.get(name) <= v);
  if (JSON.stringify(of) !== JSON.stringify(expected)) {
    throw new Error(`the globals of es${v} are not a prefix-ordered subset of the latest ones`);
  }
  if (Object.values(globals[`es${v}`]).some(value => value !== false)) {
    throw new Error(`es${v} has a global that is not read-only`);
  }
}
if (versions.at(-1) !== LATEST_ECMA_VERSION) throw new Error('the last version with globals is not the latest');
// normalizeConfigGlobal on the values conf/globals.js uses.
const normalized = value => {
  if (value === true) return 'writable';
  if (value === false) return 'readonly';
  throw new Error(`unexpected global value ${value}`);
};
// typescript-eslint's libs: the variables each one defines (a type, a value or both) and the libs
// it includes, both in order: the first definition of a name decides its kind.
const parserPath = require.resolve('@typescript-eslint/parser', { paths: [path.join(root, 'build/eval/spider-byte')] });
const scopeManager = path.dirname(require.resolve('@typescript-eslint/scope-manager/package.json', { paths: [parserPath] }));
const tsVersion = JSON.parse(fs.readFileSync(path.join(scopeManager, 'package.json'), 'utf8')).version;
const { lib } = require(path.join(scopeManager, 'dist/lib/index.js'));
const libName = new Map([...lib].map(([name, definition]) => [definition, name]));
const kind = (name, variable, options) => {
  if (options.eslintImplicitGlobalSetting !== 'readonly' || options.writeable) {
    throw new Error(`${name}: ${variable} is not a read-only implicit variable`);
  }
  if (!/^[\w$]+$/.test(variable)) throw new Error(`${name}: unexpected variable name ${variable}`);
  if (options.isTypeVariable && options.isValueVariable) return 'b';
  if (options.isTypeVariable) return 't';
  if (options.isValueVariable) return 'v';
  throw new Error(`${name}: ${variable} is neither a type nor a value`);
};
const list = items => (items.length === 0 ? '[]string{}' : `[${items.map(n => `'${n}'`).join(', ')}]`);
const lines = [
  '// Code generated by tools/gen_scope_globals.mjs; DO NOT EDIT.',
  'module rules',
  '',
  `// scope_es_globals are the globals ESLint ${version} adds to the global scope for ecmaVersion`,
  `// "latest" (es${LATEST_ECMA_VERSION} of conf/globals.js), in its order; all are read-only. The globals of`,
  '// an older version are the ones that version already had (scope_es_global_versions), in the',
  '// same order.',
  `const scope_es_globals = [${names.map(n => `'${n}'`).join(', ')}]`,
  '',
  '// scope_commonjs_globals are the globals ESLint adds for sourceType "commonjs", with their',
  '// normalized values.',
  'const scope_commonjs_globals = {',
  ...Object.entries(globals.commonjs).map(([name, value]) => `\t'${name}': '${normalized(value)}'`),
  '}',
  '',
  '// scope_ecma_versions are the versions conf/globals.js has globals for.',
  `const scope_ecma_versions = [${versions.join(', ')}]`,
  '',
  `const scope_latest_ecma_version = ${LATEST_ECMA_VERSION}`,
  '',
  '// scope_es_global_versions has, for each global of scope_es_globals, the first ecmaVersion',
  '// whose globals have it; every later version has it too.',
  'const scope_es_global_versions = {',
  ...[...names].sort().map(n => `\t'${n}': ${first.get(n)}`),
  '}',
  '',
  `// scope_lib_variables has, for each lib of typescript-eslint ${tsVersion}, the implicit variables it`,
  '// defines, in order and separated by spaces: the kind (`t` a type, `v` a value, `b` both) and',
  '// the name.',
  'const scope_lib_variables = {',
  ...[...lib].map(
    ([name, definition]) => `\t'${name}': '${definition.variables.map(([variable, options]) => kind(name, variable, options) + variable).join(' ')}'`,
  ),
  '}',
  '',
  '// scope_lib_references has, for each lib of typescript-eslint, the libs it includes, in order.',
  'const scope_lib_references = {',
  ...[...lib].map(([name, definition]) => `\t'${name}': ${list(definition.libs.map(d => libName.get(d)))}`),
  '}',
  '',
];
const output = path.join(root, 'rules/scope_globals.v');
fs.writeFileSync(output, lines.join('\n'));
execFileSync(process.env.V ?? 'v', ['fmt', '-w', output], { stdio: 'inherit' });
