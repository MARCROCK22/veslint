// Generates rules/svelte_style_tables.v: SHORTHAND_PROPERTIES of eslint-plugin-svelte 3.24.1's
// utils/css-utils/resource.ts and the properties of known-css-properties 0.37.0 (`all`), from
// build/upstream/svelte-deps. Dev-time only: `node tools/gen_svelte_style_tables.mjs` (with V=<path
// to v> if `v` is not in PATH; it formats the output with v fmt).
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { createRequire } from 'node:module';

const root = path.resolve(import.meta.dirname, '..');
const deps = path.join(root, 'build/upstream/svelte-deps/node_modules');
const require = createRequire(path.join(deps, 'x.js'));
const { all } = require('known-css-properties');
const { SHORTHAND_PROPERTIES } = await import(path.join(deps, 'eslint-plugin-svelte/lib/utils/css-utils/resource.js'));
const version = name => JSON.parse(fs.readFileSync(path.join(deps, name, 'package.json'), 'utf8')).version;
const str = s => `'${s}'`;
const out = [
  'module rules',
  '',
  `// Generated by tools/gen_svelte_style_tables.mjs from eslint-plugin-svelte ${version('eslint-plugin-svelte')} and`,
  `// known-css-properties ${version('known-css-properties')}: do not edit.`,
  '',
  '// svst_shorthand_properties is SHORTHAND_PROPERTIES: the longhand properties of each shorthand.',
  'const svst_shorthand_properties = {',
  ...[...SHORTHAND_PROPERTIES].map(([k, v]) => `\t${str(k)}: [${v.map(str).join(', ')}]`),
  '}',
  '',
  "// svst_known_css_properties are known-css-properties' `all`.",
  'const svst_known_css_properties = {',
  ...all.map(p => `\t${str(p)}: true`),
  '}',
  '',
];
const file = path.join(root, 'rules/svelte_style_tables.v');
fs.writeFileSync(file, out.join('\n'));
execFileSync(process.env.V ?? 'v', ['fmt', '-w', file], { stdio: 'ignore' });
console.log(`${SHORTHAND_PROPERTIES.size} shorthands, ${all.length} properties`);
