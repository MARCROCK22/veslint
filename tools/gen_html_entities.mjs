// Generates rules/html_entities.v, the named character references of HTML as the installed
// `entities` package (what eslint-plugin-unicorn imports) decodes them, and
// tests/html_attribute_cases.json, inputs with what its decodeHTMLAttribute gives for them
// (the html_attribute_test.v part of rules/rules_test.v checks html_decode_attribute against it). The names are those of the
// installed `character-entities` (the 2125 of the HTML standard, as in `entities`). Dev-time only:
// run `node tools/gen_html_entities.mjs && v fmt -w rules/html_entities.v` when the pinned packages
// change.
import fs from 'node:fs';
import {createRequire} from 'node:module';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const require = createRequire(path.join(root, 'build/eval/spider-byte/package.json'));
const {decodeHTMLAttribute} = require('entities');
const {version} = JSON.parse(fs.readFileSync(path.join(root, 'build/eval/spider-byte/node_modules/entities/package.json'), 'utf8'));
const {characterEntities} = require('character-entities');

const vString = text => [...Buffer.from(text, 'utf8')].map(byte => `\\x${byte.toString(16).padStart(2, '0')}`).join('');
const names = Object.keys(characterEntities).sort();
const values = [];
const legacy = [];
for (const name of names) {
  const value = decodeHTMLAttribute(`&${name};`);
  if (value === `&${name};`) {
    throw new Error(`entities does not decode &${name};`);
  }
  values.push([name, value]);
  // A name that also works without its semicolon (at the end of the input).
  if (decodeHTMLAttribute(`&${name}`) === value) {
    legacy.push(name);
  }
}
let source = `module rules

// Generated by tools/gen_html_entities.mjs from entities ${version}; do not edit.

// html_entities maps the name of a named character reference of HTML (without its \`;\`) to its
// characters.
const html_entities = {
`;
for (const [name, value] of values) {
  source += `\t'${name}': '${vString(value)}'\n`;
}
source += `}

// html_legacy_entities are the names that also work without their \`;\`.
const html_legacy_entities = {
`;
for (const name of legacy) {
  source += `\t'${name}': true\n`;
}
source += '}\n';
fs.writeFileSync(path.join(root, 'rules/html_entities.v'), source);

// The cases.
const inputs = new Set();
for (const name of names) {
  for (const suffix of [';', '', '=', 'a', '0', ' ', ';x']) {
    inputs.add(`&${name}${suffix}`);
  }
  inputs.add(`&${name.slice(0, -1)}`);
  inputs.add(`&${name.slice(0, -1)};`);
  inputs.add(`&${name}${name}`);
}
for (const text of ['', 'plain', '&', '&&', '&;', '&#', '&#;', '&#x', '&#X;', '&#x;', '&#0;', '&#65', '&#65;',
  '&#065;x', '&#x41', '&#X41;', '&#x41g', '&#xd800;', '&#xDFFF;', '&#x10ffff;', '&#x110000;',
  '&#99999999999999999999999;', '&#128;', '&#129;', '&#141;', '&#150;', '&#159;', '&#160;', '&#127;',
  '&#1;', '&#55296', '&#x1F600;', '&#x7f', '&amp;amp;', '&ampx', '&amp=', '&amp1', '&amp ', '&notin',
  '&notit;', '&noti', '&not=', '&notx', '&lt&gt', '&ltx', '&AMP', '&AMp;', '&Amp;', '&#38;amp;',
  './&#63;query', './&quest;query', './&#63query', './&#128;.png', './one.png?a=1&amp;b=2 1x', '&period;/x',
  '&#32;./x', 'http&colon;foo', '&#102;ile.png', '&ensp;', '&nbsp', '&nbspx', '&nbsp;x']) {
  inputs.add(text);
}
let seed = 0x0e_17_17;
function next() {
  seed = (Math.imul(seed, 1_103_515_245) + 12_345) >>> 0;
  return seed >>> 8;
}
const pieces = ['&', '#', 'x', 'X', ';', '=', '0', '1', '9', 'a', 'f', 'g', 'amp', 'lt', 'not', 'in', 'ε', ' ', '&#', '&#x',
  'copy', 'COPY', 'sup', '2', 'frac', '12', 'é'];
for (let n = 0; n < 4000; n++) {
  let text = '';
  const length = 1 + (next() % 8);
  for (let i = 0; i < length; i++) {
    text += pieces[next() % pieces.length];
  }
  inputs.add(text);
}
const cases = [...inputs].map(input => [input, decodeHTMLAttribute(input)]);
fs.writeFileSync(path.join(root, 'tests/html_attribute_cases.json'), JSON.stringify({entities: version, cases}) + '\n');
console.log(`${values.length} names (${legacy.length} without a semicolon), ${cases.length} cases`);
