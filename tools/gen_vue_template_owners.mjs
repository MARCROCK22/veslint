// Generates rules/vue_template_owners.v: the rules of eslint-plugin-vue 10.12.1 whose create() calls
// vue-eslint-parser's defineTemplateBodyVisitor, so that the first of them ESLint creates walks the
// template in its Program:exit (parser-services.ts). Each rule is found by running it, with ESLint
// 10.15.0 and vue-eslint-parser 10.4.2, before a sentinel rule that calls defineTemplateBodyVisitor
// itself: the rule took the traversal when the sentinel's template listener runs before the
// sentinel's own Program:exit. A rule is run with no options and with each `options` of its upstream
// cases (tests/rules/vue/<rule>/upstream.json) on a few .vue files; the rules whose answer depends on
// them are listed with the condition (vue_template_owner in vue_template.v reads it).
//
//   node tools/gen_vue_template_owners.mjs && v fmt -w rules/vue_template_owners.v
import fs from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const require = createRequire(import.meta.url);
const { Linter } = require(path.join(ROOT, 'build/eval/spider-byte/node_modules/eslint'));
const tsParser = require(path.join(ROOT, 'build/eval/spider-byte/node_modules/@typescript-eslint/parser/dist/index.js'));
const vueParser = require(path.join(ROOT, 'build/upstream/vue-deps/node_modules/vue-eslint-parser'));
const vue = require(path.join(ROOT, 'build/upstream/vue-deps/node_modules/eslint-plugin-vue'));

// Files with a templateBody: <script setup lang="ts">, an Options API <script lang="ts">, no script.
const FILES = {
  setup: '<template>\n  <div :a="b" @click="c">{{ d }}</div>\n</template>\n<script setup lang="ts">\nconst b = 1\n</script>\n<style>\n.a { color: v-bind(b) }\n</style>\n',
  options: '<template>\n  <div :a="b" @click="c">{{ d }}</div>\n</template>\n<script lang="ts">\nexport default { data() { return { b: 1 } } }\n</script>\n',
  template: '<template>\n  <div>{{ a }}</div>\n</template>\n',
};
// The conditions the runs show, checked against the rules' sources.
const CONDITIONS = {
  'no-restricted-static-attribute': 'options', // `if (context.options.length === 0) return {}`
  'no-restricted-v-on': 'options', // the same
  'no-unsupported-features': 'version', // `if (!version) return {}`
  'require-explicit-slots': 'ts_script', // some top-level <script> with lang="ts"
};

let log;
const sentinel = {
  meta: {},
  create: context =>
    context.sourceCode.parserServices.defineTemplateBodyVisitor({ VElement: () => log.push('template') }, { 'Program:exit': () => log.push('exit') }),
};
function takes(rule, options, code) {
  log = [];
  const config = {
    files: ['**/*.vue'],
    languageOptions: { parser: vueParser, parserOptions: { parser: tsParser, ecmaVersion: 'latest', sourceType: 'module' } },
    plugins: { vue, sentinel: { rules: { sentinel } } },
    rules: { [`vue/${rule}`]: ['error', ...options], 'sentinel/sentinel': 'error' },
  };
  const messages = new Linter().verify(code, config, 'test.vue');
  if (messages.some(m => m.fatal || m.ruleId === null)) return null;
  return log[0] === 'template';
}

const always = [];
const conditional = [];
for (const rule of Object.keys(vue.rules).sort()) {
  const optionsList = new Set(['[]']);
  const upstream = path.join(ROOT, 'tests/rules/vue', rule, 'upstream.json');
  if (fs.existsSync(upstream)) {
    for (const c of JSON.parse(fs.readFileSync(upstream, 'utf8')).cases) if (c.options) optionsList.add(JSON.stringify(c.options));
  }
  const answers = new Set();
  for (const options of optionsList) {
    for (const code of Object.values(FILES)) {
      const answer = takes(rule, JSON.parse(options), code);
      if (answer !== null) answers.add(answer);
    }
  }
  if (!answers.has(true)) continue;
  if (answers.size === 1) {
    if (CONDITIONS[rule]) throw new Error(`vue/${rule} no longer depends on its condition`);
    always.push(rule);
  } else if (CONDITIONS[rule]) {
    conditional.push(rule);
  } else {
    throw new Error(`vue/${rule} takes the traversal only in some runs: add its condition`);
  }
}
for (const rule of Object.keys(CONDITIONS)) {
  if (!conditional.includes(rule)) throw new Error(`vue/${rule} has a condition but takes the traversal in every run`);
}

const out = [
  '// Generated by tools/gen_vue_template_owners.mjs from eslint-plugin-vue 10.12.1: do not edit.',
  'module rules',
  '',
  '// vue_template_owners are the rules whose create() calls defineTemplateBodyVisitor on a .vue file',
  "// with a templateBody: always (''), or with a condition: 'options' (any options), 'version' (a",
  "// truthy `version` option), 'ts_script' (a top-level <script lang=\"ts\">).",
  'const vue_template_owners = {',
  ...always.map(rule => `\t'vue/${rule}': ''`),
  ...conditional.map(rule => `\t'vue/${rule}': '${CONDITIONS[rule]}'`),
  '}',
  '',
];
fs.writeFileSync(path.join(ROOT, 'rules/vue_template_owners.v'), out.join('\n'));
console.log(`rules/vue_template_owners.v: ${always.length} rules, ${conditional.length} with a condition`);
