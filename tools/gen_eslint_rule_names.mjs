// Generates rules/eslint_rule_names.v: the rule ids that exist in the ESLint and typescript-eslint
// installed by tests/eval_spider_byte.sh in build/eval. A directive comment that names a rule
// outside them gets ESLint's "Definition for rule … was not found." Dev-time only: run
// `node tools/gen_eslint_rule_names.mjs` (with V=<path to v> if `v` is not in PATH) after changing
// those versions; it formats the output with v fmt.
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { execFileSync } from 'node:child_process';

const root = path.resolve(import.meta.dirname, '..');
const modules = path.join(root, 'build/eval/spider-byte/node_modules');
const require = createRequire(path.join(root, 'build/eval/spider-byte/package.json'));
const { builtinRules } = require('eslint/use-at-your-own-risk');
const plugin = require('@typescript-eslint/eslint-plugin');
const version = name => JSON.parse(fs.readFileSync(path.join(modules, name, 'package.json'), 'utf8')).version;
const core = [...builtinRules.keys()].sort();
const typescript = Object.keys(plugin.rules).sort();
const list = names => `[${names.map(n => `'${n}'`).join(', ')}]`;
const lines = [
  '// Code generated by tools/gen_eslint_rule_names.mjs; DO NOT EDIT.',
  'module rules',
  '',
  `// eslint_core_rule_names are the rules of ESLint ${version('eslint')} (also the deprecated ones).`,
  `pub const eslint_core_rule_names = ${list(core)}`,
  '',
  `// typescript_eslint_rule_names are the rules of typescript-eslint ${version('@typescript-eslint/eslint-plugin')}, without the`,
  '// `@typescript-eslint/` prefix.',
  `pub const typescript_eslint_rule_names = ${list(typescript)}`,
  '',
];
const file = path.join(root, 'rules/eslint_rule_names.v');
fs.writeFileSync(file, lines.join('\n'));
execFileSync(process.env.V || 'v', ['fmt', '-w', file], { stdio: 'inherit' });
console.log(`${core.length} core rules, ${typescript.length} typescript-eslint rules`);
