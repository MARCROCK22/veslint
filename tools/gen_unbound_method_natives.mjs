// Generates rules/unbound_method_natives.v: the "natively bound" static members of the globals of
// typescript-eslint's unbound-method rule, computed like the rule does when it loads, with the Node
// that runs this script (use the Node that runs the reference ESLint: the list depends on its
// version). Dev-time only: run `node tools/gen_unbound_method_natives.mjs` (with V=<path to v> if
// `v` is not in PATH); it formats the output with v fmt.
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';

// SUPPORTED_GLOBALS of dist/rules/unbound-method.js (typescript-eslint 8.62.0).
const SUPPORTED_GLOBALS = ['Number', 'Object', 'String', 'RegExp', 'Symbol', 'Array', 'Proxy', 'Date', 'Atomics',
  'Reflect', 'console', 'Math', 'JSON', 'Intl'];
const names = SUPPORTED_GLOBALS.flatMap(namespace => {
  if (!(namespace in globalThis)) {
    return [];
  }
  const object = globalThis[namespace];
  return Object.getOwnPropertyNames(object)
    .filter(name => !name.startsWith('_') && typeof object[name] === 'function')
    .map(name => `${namespace}.${name}`);
});
const root = path.resolve(import.meta.dirname, '..');
const lines = [
  '// Code generated by tools/gen_unbound_method_natives.mjs; DO NOT EDIT.',
  'module rules',
  '',
  `// ubm_natively_bound_members are the nativelyBoundMembers of unbound-method on Node ${process.version}.`,
  `const ubm_natively_bound_members = [${names.map(n => `'${n}'`).join(', ')}]`,
  '',
];
const output = path.join(root, 'rules/unbound_method_natives.v');
fs.writeFileSync(output, lines.join('\n'));
execFileSync(process.env.V ?? 'v', ['fmt', '-w', output], { stdio: 'inherit' });
