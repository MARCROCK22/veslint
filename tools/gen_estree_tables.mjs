// Generates estree/tables.v: the NodeType and Key enums and the visitor keys of
// @typescript-eslint/visitor-keys 8.62.0.
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';

// The root of the project.
const ROOT = path.resolve(import.meta.dirname, '..');
const require = createRequire(path.join(ROOT, 'build/eval/spider-byte/package.json'));
const { AST_NODE_TYPES } = require('@typescript-eslint/types');
const { visitorKeys } = require('@typescript-eslint/visitor-keys');
const vkPkg = require('@typescript-eslint/visitor-keys/package.json');

const snake = s => s.replace(/^TS/, 'ts_').replace(/^JSX/, 'jsx_').replace(/([a-z0-9])([A-Z])/g, '$1_$2').replace(/([A-Z]+)([A-Z][a-z])/g, '$1_$2').toLowerCase();
const keyword = new Set(['in', 'const', 'static', 'type', 'import', 'module', 'return', 'match', 'select', 'none', 'or', 'as', 'is', 'go', 'struct', 'union', 'unsafe', 'shared', 'lock', 'rlock', 'atomic', 'asm', 'assert', 'break', 'continue', 'defer', 'else', 'enum', 'false', 'for', 'fn', 'goto', 'if', 'interface', 'mut', 'nil', 'pub', 'sizeof', 'true', 'typeof', 'volatile', 'spawn', 'isreftype', '__global', 'default', 'global', 'abstract', 'await', 'out', 'implements', 'extends', 'declare']);
const vname = s => { const n = snake(s); return keyword.has(n) ? n + '_' : n; };

const types = Object.keys(AST_NODE_TYPES);
// The most properties a node of each type had over the corpus of tests/estree/run.sh (a capacity
// hint for the arrays of properties).
const caps = JSON.parse(fs.readFileSync(new URL('./estree_prop_caps.json', import.meta.url), 'utf8'));
const keys = ['abstract', 'accessibility', 'alternate', 'argument', 'arguments', 'asserts', 'async', 'attributes', 'await', 'bigint', 'block', 'body', 'callee', 'cases', 'checkType', 'children', 'closingElement', 'closingFragment', 'computed', 'consequent', 'const', 'constraint', 'declaration', 'declarations', 'declare', 'decorators', 'default', 'definite', 'delegate', 'directive', 'discriminant', 'elements', 'elementType', 'elementTypes', 'exported', 'exportKind', 'expression', 'expressions', 'exprName', 'extends', 'extendsType', 'falseType', 'finalizer', 'generator', 'global', 'handler', 'id', 'implements', 'imported', 'importKind', 'in', 'indexType', 'init', 'initializer', 'key', 'kind', 'label', 'left', 'literal', 'local', 'members', 'meta', 'method', 'moduleReference', 'name', 'namespace', 'nameType', 'object', 'objectType', 'openingElement', 'openingFragment', 'operator', 'optional', 'options', 'out', 'override', 'param', 'parameter', 'parameterName', 'parameters', 'params', 'prefix', 'properties', 'property', 'qualifier', 'quasi', 'quasis', 'raw', 'readonly', 'regex', 'returnType', 'right', 'selfClosing', 'shorthand', 'source', 'sourceType', 'specifiers', 'static', 'superClass', 'superTypeArguments', 'tag', 'tail', 'test', 'trueType', 'typeAnnotation', 'typeArguments', 'typeName', 'typeParameter', 'typeParameters', 'types', 'update', 'value'];
for (const t of types) for (const k of visitorKeys[t] ?? []) if (!keys.includes(k)) throw new Error(`visitor key ${k} of ${t} missing`);

let out = `module estree

// Generated by tools/gen_estree_tables.mjs from @typescript-eslint/types and
// @typescript-eslint/visitor-keys ${vkPkg.version}; do not edit.

// NodeType is the \`type\` of an ESTree node (AST_NODE_TYPES of typescript-estree).
pub enum NodeType as u8 {
${types.map(t => `\t${vname(t)}`).join('\n')}
}

const node_type_names = [${types.map(t => `'${t}'`).join(', ')}]!

// Key is the name of a property of an ESTree node.
pub enum Key as u8 {
${keys.map(k => `\t${vname(k)}`).join('\n')}
}

const key_names = [${keys.map(k => `'${k}'`).join(', ')}]!

// prop_caps are, per NodeType, how many properties a node of it has at most (the capacity of
// EsNode.props; tools/prop_caps.json counts them over the corpus).
const prop_caps = [${types.map(t => `u8(${Math.max(caps[t] ?? 4, 1)})`).join(', ')}]!

// visitor_keys are, per NodeType, the keys ESLint's Traverser visits, in its order.
const visitor_keys = [
${types.map(t => `\t[${(visitorKeys[t] ?? []).map(k => `Key.${vname(k)}`).join(', ')}]${(visitorKeys[t] ?? []).length ? '' : 'Key{}'}, // ${t}`).join('\n')}
]
`;
// An empty list needs a type: []Key{}.
out = out.replace(/\[\]Key\{\}, \/\//g, '[]Key{}, //');
fs.writeFileSync(process.argv[2], out);
