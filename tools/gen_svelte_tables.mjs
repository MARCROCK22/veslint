// Generates svelte/tables.v, the tables of the Svelte 5.56.0 compiler's parser that svelte/ ports:
// the named character references of src/compiler/phases/1-parse/utils/entities.js in their
// order (decode_character_references tries them in that order: the first that matches wins), and
// the reserved words of src/utils.js (read_identifier rejects them); and the implicit variables of
// @typescript-eslint/scope-manager 8.72.2's global scope.
//
//   node tools/gen_svelte_tables.mjs svelte/tables.v && v fmt -w svelte/tables.v
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const ROOT = path.resolve(import.meta.dirname, '..');
const SVELTE = path.join(ROOT, 'build/upstream/svelte-deps/node_modules/svelte');
const version = JSON.parse(fs.readFileSync(path.join(SVELTE, 'package.json'), 'utf8')).version;
const entities = (await import(pathToFileURL(path.join(SVELTE, 'src/compiler/phases/1-parse/utils/entities.js')))).default;
const utils = fs.readFileSync(path.join(SVELTE, 'src/utils.js'), 'utf8');
const reservedText = utils.slice(utils.indexOf('const RESERVED_WORDS = ['), utils.indexOf('];', utils.indexOf('const RESERVED_WORDS = [')) + 1);
const reserved = eval(reservedText.slice(reservedText.indexOf('[')));

const q = s => `'${s}'`;
const { lib } = (await import(pathToFileURL(path.join(ROOT, 'build/upstream/svelte-deps/node_modules/@typescript-eslint/scope-manager/dist/lib/index.js')))).default;
const libs = new Set([lib.get('esnext')]);
for (const l of libs) for (const dep of l.libs) libs.add(dep);
const globals = new Map();
for (const l of libs)
  for (const [name, v] of l.variables) {
    const old = globals.get(name) ?? 0;
    globals.set(name, old | (v.isTypeVariable ? 1 : 0) | (v.isValueVariable ? 2 : 0));
  }
globals.set('const', 1);
const out = [];
out.push(`// Code generated by tools/gen_svelte_tables.mjs from svelte ${version}; DO NOT EDIT.`);
out.push('module svelte', '');
out.push('// entity_names are the named character references (without `&`), in the order the compiler');
out.push('// tries them; entity_codes their code points.');
out.push(`const entity_names = [${Object.keys(entities).map(q).join(', ')}]`, '');
out.push(`const entity_codes = [${Object.values(entities).join(', ')}]`, '');
out.push('// reserved_words are the words read_identifier rejects (unexpected_reserved_word).');
out.push(`const reserved_words = [${reserved.map(q).join(', ')}]`, '');
// The order of the implicit variables in the global scope (what scope.variables lists).
const { analyze } = await import(pathToFileURL(path.join(ROOT, 'build/upstream/svelte-deps/node_modules/@typescript-eslint/scope-manager/dist/index.js')));
const sm = analyze({ type: 'Program', body: [], sourceType: 'module', range: [0, 0], loc: { start: { line: 1, column: 0 }, end: { line: 1, column: 0 } } }, { sourceType: 'module' });
const order = sm.globalScope.variables.map(v => v.name);
out.push('// lib_global_order: the implicit variables in the order of the global scope\'s variables.');
out.push(`const lib_global_order = [${order.map(q).join(', ')}]`, '');
out.push('// lib_globals are the implicit variables typescript-eslint\'s scope manager puts in the global');
out.push('// scope (the lib `esnext` with its dependencies, and `const`), by name: 1 a type, 2 a value, 3 both.');
out.push('const lib_globals = {');
for (const [name, flags] of [...globals].sort((a, b) => (a[0] < b[0] ? -1 : 1))) out.push(`\t${q(name)}: u8(${flags})`);
out.push('}', '');
fs.writeFileSync(process.argv[2], out.join('\n') + '\n');
