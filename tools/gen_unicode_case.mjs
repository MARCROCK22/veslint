// Generates rules/unicode_case_data.v and tests/unicode_case_cases.json: what
// String.prototype.toUpperCase and toLowerCase give in the Node that runs this script (V8 and its
// ICU, the engine ESLint runs on), for rules/unicode_case.v. typescript-eslint compares names
// with them (naming-convention's formats) and ESLint evaluates them in constant expressions.
// Node runs this script at development time only; veslint never runs Node.
//
// Usage: node tools/gen_unicode_case.mjs > rules/unicode_case_data.v && v fmt -w rules/unicode_case_data.v
import fs from 'node:fs';
import path from 'node:path';

const lastCodePoint = 0x10ffff;
const codePoints = text => [...text].map(c => c.codePointAt(0));

// The code points a conversion changes: to one code point (`simple`, as pairs) or to several
// (`special`, the code point and up to three of the result, filled with zeros).
function mappings(convert) {
  const simple = [];
  const special = [];
  for (let cp = 0; cp <= lastCodePoint; cp++) {
    if (cp >= 0xd800 && cp <= 0xdfff) {
      continue;
    }
    const text = String.fromCodePoint(cp);
    const result = codePoints(convert(text));
    if (result.length === 1 && result[0] === cp) {
      continue;
    }
    if (result.length === 1) {
      simple.push(cp, result[0]);
    } else if (result.length <= 3 && !result.includes(0)) {
      special.push(cp, ...result, ...Array(3 - result.length).fill(0));
    } else {
      throw new Error(`U+${cp.toString(16)} converts to ${result.length} code points`);
    }
  }
  return { simple, special };
}
const upper = mappings(text => text.toUpperCase());
const lower = mappings(text => text.toLowerCase());

// Checks of what rules/unicode_case.v assumes: a lone surrogate stays, and the only conversion
// that looks at the neighbours is the one of U+03A3 to lower case (the final sigma).
for (let unit = 0xd800; unit <= 0xdfff; unit++) {
  const text = String.fromCharCode(unit);
  if (text.toUpperCase() !== text || text.toLowerCase() !== text) {
    throw new Error(`the lone surrogate ${unit.toString(16)} is converted`);
  }
}
const neighbours = ['a', 'A', '1', ' ', '.', "'", '́', 'Σ', 'σ', 'ͅ', '\u{10400}', 'ß'];
for (let cp = 0; cp <= lastCodePoint; cp++) {
  if ((cp >= 0xd800 && cp <= 0xdfff) || cp === 0x3a3) {
    continue;
  }
  const text = String.fromCodePoint(cp);
  for (const other of neighbours) {
    for (const [before, after] of [[other, ''], ['', other], [other, other]]) {
      const whole = before + text + after;
      if (whole.toUpperCase() !== before.toUpperCase() + text.toUpperCase() + after.toUpperCase()) {
        throw new Error(`the upper case of U+${cp.toString(16)} depends on its neighbours`);
      }
      // The neighbour may be a sigma whose own conversion depends on this code point.
      if (other !== 'Σ' && whole.toLowerCase() !== before.toLowerCase() + text.toLowerCase() + after.toLowerCase()) {
        throw new Error(`the lower case of U+${cp.toString(16)} depends on its neighbours`);
      }
    }
  }
}
if ('Σ'.toLowerCase() !== 'σ' || 'aΣ'.toLowerCase() !== 'aς' || 'aΣa'.toLowerCase() !== 'aσa') {
  throw new Error('the final sigma is not converted as expected');
}

// Cases for rules/unicode_case_test.v, as UTF-16 units: chosen ones, and strings made of the
// characters that matter around a sigma, in an order that depends only on the seed.
const chosen = [
  '', 'abc', 'ABC', 'aBc1_', 'straße', 'STRASSE', 'ẞ', 'ŉ', 'ǰ', 'ﬁ', 'ﬃ', 'ΐ', 'ᾈ', 'ᾳ', 'ᾼ', 'İ', 'ı', 'i̇', 'I', 'ǅ', 'ǆ', 'Ǆ',
  'Émile', 'ñandú', 'ΑΣ', 'ΑΣΑ', 'Σ', 'ΣΑ', 'Α Σ', 'ΑΣ.', "Α'Σ", "ΑΣ'Α", 'ΑΣ́', 'ΆΣ', 'ΑΣΣ', 'ςσΣ', 'ὈΔΥΣΣΕΎΣ',
  '\u{10400}\u{10428}', '\u{1e900}\u{1e922}', 'Ꭰꭰ', 'აᲐ', 'KKÅ', 'µ', 'ÿ', 'ſ', 'ͅ', 'ǅΣ', '1Σ', 'aͅΣ', 'ΣͅΑ',
  '\ud800a', 'a\udc00', '𐐀', '\udc00\ud801', 'A\ud83d', '日本語', 'Ⅰⅰ', 'Ⓐⓐ', 'ꟸ', 'ℊ',
];
let seed = 20261010;
function random(count) {
  seed = (Math.imul(seed, 1103515245) + 12345) >>> 0;
  return (seed >>> 8) % count;
}
const pool = ['a', 'A', 'Σ', 'Σ', 'σ', 'ς', "'", '.', ':', ' ', '1', '́', 'ͅ', '­', 'ʰ', 'ß', 'İ', 'ǅ', '\u{10400}', '\u{1d400}', '\ud800', '_', 'Ⅷ'];
const texts = [...chosen];
for (let i = 0; i < 600; i++) {
  let text = '';
  for (let j = 0, n = 1 + random(7); j < n; j++) {
    text += pool[random(pool.length)];
  }
  texts.push(text);
}
const units = text => Array.from({ length: text.length }, (_, i) => text.charCodeAt(i));
const cases = texts.map(text => ({ units: units(text), upper: units(text.toUpperCase()), lower: units(text.toLowerCase()) }));
fs.writeFileSync(path.resolve(import.meta.dirname, '../tests/unicode_case_cases.json'), JSON.stringify({ node: process.version, cases }) + '\n');

const list = values => `[${values.map(n => `u32(0x${n.toString(16)})`).join(', ')}]`;
const out = [
  '// Code generated by tools/gen_unicode_case.mjs; DO NOT EDIT.',
  '',
  'module rules',
  '',
  `// The case conversions of the strings of Node ${process.version} (V8 ${process.versions.v8}, ICU ${process.versions.icu}, Unicode ${process.versions.unicode}).`,
  '',
  '// The code points toUpperCase changes to one code point, as pairs sorted by the first.',
  `const unicode_upper_simple = ${list(upper.simple)}`,
  '',
  '// The code points toUpperCase changes to two or three: each one and its result, filled with a',
  '// zero when it has two. Sorted by the first.',
  `const unicode_upper_special = ${list(upper.special)}`,
  '',
  '// The same for toLowerCase. U+03A3 is here as if nothing were around it.',
  `const unicode_lower_simple = ${list(lower.simple)}`,
  '',
  `const unicode_lower_special = ${list(lower.special)}`,
  '',
];
process.stdout.write(out.join('\n'));
