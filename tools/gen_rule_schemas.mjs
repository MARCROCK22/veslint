// Generates rules/rule_schemas.v: for each ported rule, the JSON schema ESLint validates its options
// with (Config.getRuleOptionsSchema of the rule's meta.schema: the list form becomes an array schema
// with those items); and, for every rule of ESLint and of typescript-eslint that has them, the
// meta.defaultOptions ESLint merges under the options of the rule before it validates them and when
// it normalizes a configuration. They come from the ESLint and typescript-eslint installed by
// tests/eval_spider_byte.sh in build/eval. rules/json_schema.v validates with them like ESLint's
// ajv does; a schema that uses a keyword that validator does not implement stops the generation.
// Dev-time only: run `node tools/gen_rule_schemas.mjs` (with V=<path to v> if `v` is not in PATH)
// after changing those versions, and then tools/gen_rule_option_cases.mjs; it formats the output
// with v fmt.
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { execFileSync } from 'node:child_process';
import { portedRules, checkSchema, ruleDefaults, seyfertPlugin, pluginOf } from './rule_schema_support.mjs';

const root = path.resolve(import.meta.dirname, '..');
const modules = path.join(root, 'build/eval/spider-byte/node_modules');
const require = createRequire(path.join(root, 'build/eval/spider-byte/package.json'));
const plugin = require('@typescript-eslint/eslint-plugin');
const { builtinRules } = require('eslint/use-at-your-own-risk');
const { Config } = require(path.join(modules, 'eslint/lib/config/config.js'));
const version = name => JSON.parse(fs.readFileSync(path.join(modules, name, 'package.json'), 'utf8')).version;

// A V string literal: `$` would start an interpolation.
const literal = text => `'${text.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$')}'`;

const schemas = [];
const plugins = { '': { rules: Object.fromEntries(builtinRules) }, '@typescript-eslint': plugin, seyfert: seyfertPlugin(root) };
for (const id of portedRules(root)) {
  const [namespace, owner, name] = pluginOf(id, plugins);
  const rule = owner.rules[name];
  if (!rule) {
    throw new Error(`${namespace} has no rule ${name}`);
  }
  const schema = Config.getRuleOptionsSchema(rule);
  if (schema === null) {
    throw new Error(`${name}: \`schema: false\` (no validation) is not supported`);
  }
  checkSchema(schema, name);
  schemas.push(`\t'${id}': ${literal(JSON.stringify(schema))}`);
}
const defaults = ruleDefaults(builtinRules, plugins).map(([id, options]) => `\t'${id}': ${literal(JSON.stringify(options))}`);
const lines = [
  '// Code generated by tools/gen_rule_schemas.mjs; DO NOT EDIT.',
  'module rules',
  '',
  `// rule_option_schemas has, for each ported rule, the JSON schema ESLint ${version('eslint')} validates its options`,
  `// with: getRuleOptionsSchema of the meta.schema of typescript-eslint ${version('@typescript-eslint/eslint-plugin')} (a schema in list`,
  '// form becomes an array schema with those items).',
  'const rule_option_schemas = {',
  ...schemas,
  '}',
  '',
  '// eslint_rule_default_options are the meta.defaultOptions of the rules of ESLint and of',
  '// typescript-eslint that have them, by rule id: ESLint merges the options of a rule over them',
  '// (deepMergeArrays) before it validates them and when it normalizes a configuration.',
  'const eslint_rule_default_options = {',
  ...defaults,
  '}',
  '',
];
const file = path.join(root, 'rules/rule_schemas.v');
fs.writeFileSync(file, lines.join('\n'));
execFileSync(process.env.V || 'v', ['fmt', '-w', file], { stdio: 'inherit' });
console.log(`${schemas.length} schemas, ${defaults.length} rules of ESLint and typescript-eslint with meta.defaultOptions`);
